-- An independent source snapshot preserves user-visible citations and saved sources.
-- No file_storage_path or content_hash: ingestion/storage/deduplication belong to AI.
CREATE TABLE backend.document (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ai_document_id BIGINT NOT NULL UNIQUE CHECK (ai_document_id > 0),
    doc_title TEXT NOT NULL,
    source_name VARCHAR(255),
    source_url TEXT,
    published_at DATE,
    effective_from DATE,
    effective_to DATE,
    doc_version VARCHAR(100),
    source_type VARCHAR(30) NOT NULL DEFAULT 'OTHER'
        CHECK (source_type IN ('GOVERNMENT','REPORT','PAPER','OFFICIAL_STATISTICS','NEWS','OTHER')),
    reliability_level VARCHAR(20) CHECK (reliability_level IN ('HIGH','MEDIUM','LOW')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_document_effective_period CHECK (
        effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from)
);
INSERT INTO backend.document(document_id, ai_document_id, doc_title, source_name, source_url,
    published_at, effective_from, effective_to, doc_version, source_type, reliability_level, created_at, updated_at)
SELECT document_id, document_id, doc_title, source_name, source_url,
    published_at, effective_from, effective_to, doc_version, source_type, reliability_level, created_at, updated_at
FROM ai.document;
SELECT setval(pg_get_serial_sequence('backend.document','document_id'),
    COALESCE((SELECT max(document_id) FROM backend.document), 1),
    EXISTS (SELECT 1 FROM backend.document));

ALTER TABLE backend.saved_source DROP CONSTRAINT saved_source_document_id_fkey;
ALTER TABLE backend.saved_source ADD CONSTRAINT saved_source_document_id_fkey
    FOREIGN KEY(document_id) REFERENCES backend.document(document_id) ON DELETE RESTRICT;

-- Save citation location before detaching the backend from mutable AI chunks.
ALTER TABLE backend.evidence ADD COLUMN document_id BIGINT,
    ADD COLUMN page_start INTEGER CHECK (page_start > 0),
    ADD COLUMN page_end INTEGER CHECK (page_end > 0),
    ADD COLUMN section_title TEXT;
UPDATE backend.evidence e SET document_id=c.document_id, page_start=c.page_start,
    page_end=c.page_end, section_title=c.section_title FROM ai.document_chunk c WHERE e.chunk_id=c.chunk_id;
ALTER TABLE backend.evidence ALTER COLUMN document_id SET NOT NULL;
ALTER TABLE backend.evidence ADD CONSTRAINT evidence_document_id_fkey
    FOREIGN KEY(document_id) REFERENCES backend.document(document_id) ON DELETE RESTRICT;
ALTER TABLE backend.evidence ADD CONSTRAINT ck_evidence_page_range
    CHECK (page_start IS NULL OR page_end IS NULL OR page_end >= page_start);
ALTER TABLE backend.evidence DROP CONSTRAINT evidence_chunk_id_fkey;
ALTER TABLE backend.evidence RENAME COLUMN chunk_id TO ai_chunk_id;
ALTER TABLE backend.evidence ALTER COLUMN ai_chunk_id DROP NOT NULL;
CREATE INDEX idx_evidence_document ON backend.evidence(document_id);

-- External IDs are correlation values, not cross-service ORM/foreign-key dependencies.
ALTER TABLE backend.verification DROP CONSTRAINT verification_run_id_fkey;
ALTER TABLE backend.verification RENAME COLUMN run_id TO ai_run_id;
ALTER TABLE ai.retrieval_run DROP CONSTRAINT retrieval_run_task_id_fkey;
ALTER TABLE ai.retrieval_run DROP CONSTRAINT retrieval_run_claim_id_fkey;
COMMENT ON COLUMN ai.retrieval_run.task_id IS 'Backend task ID supplied in the AI job; no direct backend access';
