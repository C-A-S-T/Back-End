-- Policy changes are confirmed comparison records, not an inference from document dates.
-- Neither ingestion nor AI comparison is implemented by this migration.
CREATE TABLE backend.policy_change (
    policy_change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_key VARCHAR(160) NOT NULL,
    policy_title TEXT NOT NULL,
    category VARCHAR(30) NOT NULL,
    previous_document_id BIGINT NOT NULL
        REFERENCES backend.document(document_id) ON DELETE RESTRICT,
    current_document_id BIGINT NOT NULL
        REFERENCES backend.document(document_id) ON DELETE RESTRICT,
    change_summary TEXT NOT NULL,
    confirmed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_policy_change_key_not_blank CHECK (btrim(policy_key) <> ''),
    CONSTRAINT ck_policy_change_title_not_blank CHECK (btrim(policy_title) <> ''),
    CONSTRAINT ck_policy_change_summary_not_blank CHECK (btrim(change_summary) <> ''),
    CONSTRAINT ck_policy_change_category CHECK (
        category IN ('HOUSING', 'GOV_SUPPORT', 'EDUCATION')
    ),
    CONSTRAINT ck_policy_change_distinct_documents CHECK (
        previous_document_id <> current_document_id
    ),
    CONSTRAINT uq_policy_change_comparison UNIQUE (
        policy_key, previous_document_id, current_document_id
    )
);

-- One assessment per user and confirmed change. NULL means not yet evaluated.
CREATE TABLE backend.user_policy_change_impact (
    user_id BIGINT NOT NULL REFERENCES backend.app_user(user_id) ON DELETE RESTRICT,
    policy_change_id BIGINT NOT NULL
        REFERENCES backend.policy_change(policy_change_id) ON DELETE RESTRICT,
    requires_recheck BOOLEAN,
    impact_summary TEXT,
    evaluated_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_user_policy_change_impact PRIMARY KEY (user_id, policy_change_id)
);

CREATE INDEX idx_policy_change_confirmed
    ON backend.policy_change(confirmed_at DESC, policy_change_id DESC);
CREATE INDEX idx_policy_change_category_confirmed
    ON backend.policy_change(category, confirmed_at DESC);
CREATE INDEX idx_user_policy_change_impact_change
    ON backend.user_policy_change_impact(policy_change_id, user_id);

-- Explicit grants mirror V10; the runtime user must not need migrator privileges.
GRANT SELECT, INSERT, UPDATE, DELETE ON backend.policy_change TO cast_app;
GRANT USAGE, SELECT ON SEQUENCE backend.policy_change_policy_change_id_seq TO cast_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON backend.user_policy_change_impact TO cast_app;
