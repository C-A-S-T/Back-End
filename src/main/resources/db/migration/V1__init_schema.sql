-- C.A.S.T PostgreSQL schema v1 (draft)
-- Scope: 15 core application tables; not executed against any database.
-- Naming: conceptual User -> app_user, Query -> research_query.
-- Target: PostgreSQL 15+ supporting column-specific ON DELETE SET NULL.
-- Important: application services must refresh updated_at when updating a row.
-- Optional authentication sessions, password-reset tokens, and evaluation-run
-- tables are outside this approved 15-entity core scope.


CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_consent (
    consent_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT,
    consent_type VARCHAR(40) NOT NULL
        CHECK (consent_type IN ('TERMS', 'PRIVACY', 'AGE_14_PLUS', 'MARKETING')),
    policy_version VARCHAR(100),
    is_agreed BOOLEAN NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE document (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_title TEXT NOT NULL,
    source_name VARCHAR(255),
    source_url TEXT,
    file_storage_path TEXT,
    published_at DATE,
    effective_from DATE,
    effective_to DATE,
    doc_version VARCHAR(100),
    source_type VARCHAR(30) NOT NULL DEFAULT 'OTHER'
        CHECK (source_type IN (
            'GOVERNMENT', 'REPORT', 'PAPER', 'OFFICIAL_STATISTICS', 'NEWS', 'OTHER'
        )),
    reliability_level VARCHAR(20)
        CHECK (reliability_level IN ('HIGH', 'MEDIUM', 'LOW')),
    collected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_document_effective_period
        CHECK (effective_to IS NULL OR effective_from IS NULL
               OR effective_to >= effective_from)
);

CREATE TABLE document_chunk (
    chunk_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES document(document_id) ON DELETE RESTRICT,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    chunk_content TEXT NOT NULL,
    page_start INTEGER CHECK (page_start > 0),
    page_end INTEGER CHECK (page_end > 0),
    section_title TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_document_chunk_index UNIQUE (document_id, chunk_index),
    CONSTRAINT ck_document_chunk_page_order
        CHECK (page_end IS NULL OR page_start IS NULL OR page_end >= page_start)
);

CREATE TABLE research_query (
    query_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT,
    research_title TEXT,
    question TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE research_task (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    query_id BIGINT NOT NULL REFERENCES research_query(query_id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'CANCELED', 'FAILED')),
    current_step SMALLINT CHECK (current_step BETWEEN 1 AND 6),
    preview_summary TEXT,
    preview_updated_at TIMESTAMPTZ,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    canceled_at TIMESTAMPTZ,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Create an Answer in DRAFT state early, so Claim rows can exist before
-- the final response text has been generated.
CREATE TABLE answer (
    answer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL UNIQUE
        REFERENCES research_task(task_id) ON DELETE RESTRICT,
    answer_content TEXT,
    summary_content TEXT,
    answer_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (answer_status IN ('DRAFT', 'FINAL', 'ABORTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_final_answer_has_content
        CHECK (answer_status <> 'FINAL' OR answer_content IS NOT NULL)
);

CREATE TABLE claim (
    claim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    answer_id BIGINT NOT NULL REFERENCES answer(answer_id) ON DELETE RESTRICT,
    claim_index INTEGER NOT NULL CHECK (claim_index >= 0),
    claim_content TEXT NOT NULL,
    claim_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (claim_status IN ('DRAFT', 'CONFIRMED', 'DISCARDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_claim_answer_index UNIQUE (answer_id, claim_index)
);

CREATE TABLE verification (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_id BIGINT NOT NULL REFERENCES claim(claim_id) ON DELETE RESTRICT,
    status VARCHAR(24) NOT NULL DEFAULT 'IN_PROGRESS'
        CHECK (status IN (
            'IN_PROGRESS', 'SUPPORTED', 'CONTRADICTED', 'PARTIAL', 'INSUFFICIENT'
        )),
    verification_reason TEXT,
    ver_attempt_number INTEGER NOT NULL CHECK (ver_attempt_number >= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_verification_claim_attempt
        UNIQUE (claim_id, ver_attempt_number)
);

-- Evidence belongs to one verification attempt. Its Claim is derived through
-- verification.claim_id, avoiding two independent Claim foreign keys.
CREATE TABLE evidence (
    evidence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verification_id BIGINT NOT NULL
        REFERENCES verification(verification_id) ON DELETE RESTRICT,
    chunk_id BIGINT NOT NULL REFERENCES document_chunk(chunk_id) ON DELETE RESTRICT,
    evidence_text TEXT NOT NULL,
    evidence_relation VARCHAR(20) NOT NULL
        CHECK (evidence_relation IN ('SUPPORTS', 'CONTRADICTS', 'NEUTRAL')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE retrieval_run (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES research_task(task_id) ON DELETE RESTRICT,
    -- NULL for question-level initial retrieval before any Claim exists.
    claim_id BIGINT REFERENCES claim(claim_id) ON DELETE RESTRICT,
    -- One RetrievalRun is one search attempt. Only RETRY consumes the
    -- per-Claim automatic retry budget (1, 2, 3); initial searches use 0.
    re_attempt_number INTEGER NOT NULL DEFAULT 0,
    run_type VARCHAR(24) NOT NULL
        CHECK (run_type IN ('INITIAL', 'CLAIM_SEARCH', 'RETRY')),
    search_query TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_retrieval_run_retry_policy CHECK (
        (run_type = 'INITIAL' AND claim_id IS NULL AND re_attempt_number = 0)
        OR (run_type = 'CLAIM_SEARCH' AND claim_id IS NOT NULL AND re_attempt_number = 0)
        OR (run_type = 'RETRY' AND claim_id IS NOT NULL
            AND re_attempt_number BETWEEN 1 AND 3)
    )
);

CREATE TABLE retrieval_result (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES retrieval_run(run_id) ON DELETE RESTRICT,
    chunk_id BIGINT NOT NULL REFERENCES document_chunk(chunk_id) ON DELETE RESTRICT,
    rank INTEGER NOT NULL CHECK (rank >= 1),
    score DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_retrieval_result_rank UNIQUE (run_id, rank),
    CONSTRAINT uq_retrieval_result_chunk UNIQUE (run_id, chunk_id)
);

-- Evaluation reference data is kept separate from production queries.
-- The JSONB chunk ID list is not FK-constrained in this 15-table baseline.
CREATE TABLE evaluation_case (
    eval_case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question TEXT NOT NULL,
    reference_answer TEXT,
    expected_claims JSONB NOT NULL DEFAULT '[]'::jsonb,
    relevant_chunk_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    category VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_expected_claims_is_array
        CHECK (jsonb_typeof(expected_claims) = 'array'),
    CONSTRAINT ck_relevant_chunk_ids_is_array
        CHECK (jsonb_typeof(relevant_chunk_ids) = 'array')
);

CREATE TABLE source_folder (
    folder_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT,
    folder_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_source_folder_user_name UNIQUE (user_id, folder_name),
    -- Needed to enforce same-user folder ownership from saved_source.
    CONSTRAINT uq_source_folder_user_id UNIQUE (user_id, folder_id)
);

CREATE TABLE saved_source (
    saved_source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE RESTRICT,
    document_id BIGINT NOT NULL REFERENCES document(document_id) ON DELETE RESTRICT,
    folder_id BIGINT,
    -- First research task that caused this document to be saved, if any.
    origin_task_id BIGINT REFERENCES research_task(task_id) ON DELETE SET NULL,
    -- First insertion method; duplicate saves must not reset manual metadata.
    save_method VARCHAR(10) NOT NULL
        CHECK (save_method IN ('AUTO', 'MANUAL')),
    is_favorite BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_saved_source_user_document UNIQUE (user_id, document_id),
    CONSTRAINT fk_saved_source_owned_folder
        FOREIGN KEY (user_id, folder_id)
        REFERENCES source_folder(user_id, folder_id)
        ON DELETE SET NULL (folder_id)
);

-- Read-oriented indexes beyond those already created by PRIMARY KEY/UNIQUE.
CREATE INDEX idx_user_consent_user_time ON user_consent(user_id, occurred_at DESC);
CREATE INDEX idx_document_source_type ON document(source_type);
CREATE INDEX idx_research_query_user_created ON research_query(user_id, created_at DESC);
CREATE INDEX idx_research_task_query_created ON research_task(query_id, created_at DESC);
CREATE INDEX idx_evidence_verification ON evidence(verification_id);
CREATE INDEX idx_evidence_chunk ON evidence(chunk_id);
CREATE INDEX idx_retrieval_run_task_created ON retrieval_run(task_id, created_at DESC);
CREATE INDEX idx_retrieval_run_claim ON retrieval_run(claim_id);
-- At most one RETRY row for each Claim and retry number (1-3).
CREATE UNIQUE INDEX uq_retrieval_retry_claim_attempt
    ON retrieval_run(claim_id, re_attempt_number)
    WHERE run_type = 'RETRY';
CREATE INDEX idx_retrieval_result_chunk ON retrieval_result(chunk_id);
CREATE INDEX idx_saved_source_user_created ON saved_source(user_id, created_at DESC);
CREATE INDEX idx_saved_source_user_folder ON saved_source(user_id, folder_id);
CREATE INDEX idx_saved_source_favorite ON saved_source(user_id)
    WHERE is_favorite = TRUE;
CREATE INDEX idx_saved_source_document ON saved_source(document_id);
CREATE INDEX idx_saved_source_origin_task ON saved_source(origin_task_id);

COMMENT ON TABLE research_task IS 'One persisted execution of a user research query, including progress preview';
COMMENT ON COLUMN research_task.preview_summary IS 'Persisted mid-run preview; not the final Answer summary';
COMMENT ON COLUMN retrieval_run.re_attempt_number IS '0 for INITIAL/CLAIM_SEARCH; RETRY 1-3, one search query per run; service allocates attempts in order';
COMMENT ON TABLE evaluation_case IS 'Offline gold-set evaluation only; not used to serve end users';
COMMENT ON COLUMN saved_source.save_method IS 'AUTO or MANUAL at the first save; duplicates do not overwrite it';
COMMENT ON COLUMN document.reliability_level IS 'Nullable until the reliability scoring policy is decided';