-- User bookmarks only existing, backend-owned verification evidence.
-- Source document snapshots and AI-owned chunks are not duplicated.
CREATE TABLE backend.sentence_scrap (
    scrap_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES backend.app_user(user_id) ON DELETE RESTRICT,
    evidence_id BIGINT NOT NULL REFERENCES backend.evidence(evidence_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sentence_scrap_user_evidence UNIQUE (user_id, evidence_id)
);
CREATE INDEX idx_sentence_scrap_user_created
    ON backend.sentence_scrap(user_id, created_at DESC, scrap_id DESC);

-- Runtime grants are explicit in addition to V6's default privileges.
GRANT SELECT, INSERT, UPDATE, DELETE ON backend.sentence_scrap TO cast_app;
GRANT USAGE, SELECT ON SEQUENCE backend.sentence_scrap_scrap_id_seq TO cast_app;
